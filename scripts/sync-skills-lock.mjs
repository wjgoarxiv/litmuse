#!/usr/bin/env node
// Writes skills.lock.json: one hash, size and file count per shipped skill, plus the `npm pack` file list.
// `policy` and `budgets` are hand-owned: a sync keeps them as written. A skill without a budget and a budget whose
// skill is gone are violations until named: `--accept-new <id>` seeds the first budget, `--drop <id>` removes an
// orphan one (both repeatable). While any violation stands, nothing is written and the exit is 1.
// Only git-tracked files are measured (the pack list's plugin/skills entries when git is unavailable).
// Raise a budget by hand when a skill grows on purpose; never lower one to pass. A skill whose body moved to
// wjgoarxiv-skills is listed in `policy.movedStubs`: its same-name stub is exempt from the family floor only, and its
// own budget (hand-owned like every other) holds it to stub size.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const LOCK_PATH = join(ROOT, 'skills.lock.json');
const NOTE = 'Generated by npm run sync:lock: skills and pack. Hand-owned and kept by every sync: policy and budgets.';
const HEADROOM = 1.5;

const sha256 = (data) => createHash('sha256').update(data).digest('hex');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else acc.push(p);
  }
  return acc;
}

/**
 * Files under skillsDir that ship, relative to it: `git ls-files`, so untracked and ignored files (.DS_Store) never
 * count. Without git, the pack list's plugin/skills entries of the package that holds skillsDir; outside any
 * repo or package (test fixtures), every file on disk.
 */
export function listSkillFiles(skillsDir) {
  const git = spawnSync('git', ['ls-files', '-z', '--', '.'], { cwd: skillsDir, encoding: 'utf8' });
  if (git.status === 0) return git.stdout.split('\0').filter(Boolean).filter((f) => existsSync(join(skillsDir, f)));
  const pkgRoot = join(skillsDir, '..', '..');
  if (existsSync(join(pkgRoot, 'package.json')) && relative(pkgRoot, skillsDir).split('\\').join('/') === 'plugin/skills') {
    return packFiles(pkgRoot).filter((f) => f.startsWith('plugin/skills/')).map((f) => f.slice('plugin/skills/'.length));
  }
  return walk(skillsDir).map((f) => relative(skillsDir, f).split('\\').join('/'));
}

/** Per skill: SKILL.md bytes and hash, file count, total bytes, and one hash over every file's path and content. */
export function measureSkills(skillsDir, files = listSkillFiles(skillsDir)) {
  // Segment order (`rust/x` before `rust-ub/x`), the order a sorted directory walk gives.
  const key = (f) => f.split('/').join('\0');
  const bySkill = new Map();
  for (const f of [...files].sort((x, y) => (key(x) < key(y) ? -1 : key(x) > key(y) ? 1 : 0))) {
    const slash = f.indexOf('/');
    if (slash < 0) continue;
    const id = f.slice(0, slash);
    if (!bySkill.has(id)) bySkill.set(id, []);
    bySkill.get(id).push(f.slice(slash + 1));
  }
  const out = {};
  for (const id of [...bySkill.keys()].sort()) {
    const rels = bySkill.get(id);
    if (!rels.includes('SKILL.md')) continue;
    const root = join(skillsDir, id);
    const md = readFileSync(join(root, 'SKILL.md'));
    let bytes = 0;
    const rows = rels.map((rel) => {
      const data = readFileSync(join(root, rel));
      bytes += data.length;
      return `${rel}\t${data.length}\t${sha256(data)}\n`;
    });
    out[id] = { skillMd: { bytes: md.length, sha256: sha256(md) }, files: rows.length, bytes, sha256: sha256(rows.join('')) };
  }
  return out;
}

export function packFiles(root = ROOT) {
  const r = spawnSync('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], { cwd: root, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`npm pack --dry-run failed: ${r.stderr}`);
  return JSON.parse(r.stdout)[0].files.map((f) => f.path).sort();
}

const up = (n) => Math.ceil((n * HEADROOM) / 1000) * 1000;

/** The first budget of a new skill: its current size as the floor, half again as the ceiling. */
export function seedBudget(skill, policy = {}) {
  return {
    minSkillBytes: Math.max(policy.familyFloorBytes ?? 0, Math.floor(skill.skillMd.bytes / 100) * 100),
    maxSkillBytes: up(skill.skillMd.bytes),
    minFiles: skill.files,
    maxFiles: Math.ceil(skill.files * HEADROOM),
    maxBytes: up(skill.bytes),
  };
}

export function budgetViolations(measured, budgets, policy = {}) {
  const out = [];
  for (const id of [...new Set([...Object.keys(measured), ...Object.keys(budgets)])].sort()) {
    const m = measured[id];
    const b = budgets[id];
    if (!b) {
      out.push(`${id}: new skill without a budget (sync:lock --accept-new ${id})`);
      continue;
    }
    if (!m) {
      out.push(`${id}: budget for a missing skill (sync:lock --drop ${id})`);
      continue;
    }
    const md = m.skillMd.bytes;
    if (md < b.minSkillBytes) out.push(`${id}: SKILL.md ${md} B < budget ${b.minSkillBytes} B`);
    const stub = (policy.movedStubs ?? []).includes(id);
    if (policy.familyFloorBytes && md < policy.familyFloorBytes && !stub) out.push(`${id}: SKILL.md ${md} B < family floor ${policy.familyFloorBytes} B`);
    if (md > b.maxSkillBytes) out.push(`${id}: SKILL.md ${md} B > budget ${b.maxSkillBytes} B`);
    if (m.files < b.minFiles) out.push(`${id}: ${m.files} files < budget ${b.minFiles}`);
    if (m.files > b.maxFiles) out.push(`${id}: ${m.files} files > budget ${b.maxFiles}`);
    if (m.bytes > b.maxBytes) out.push(`${id}: ${m.bytes} B in all > budget ${b.maxBytes} B`);
  }
  return out;
}

/** Budgets are kept as written; only an id named in acceptNew is seeded and only one named in drop is removed. */
export function buildLock({ skillsDir, pack, previous = {}, acceptNew = [], drop = [] }) {
  const policy = previous.policy ?? {};
  const skills = measureSkills(skillsDir);
  const kept = previous.budgets ?? {};
  for (const id of acceptNew) if (!skills[id] || kept[id]) throw new Error(`--accept-new ${id}: not a new skill`);
  for (const id of drop) if (skills[id] || !kept[id]) throw new Error(`--drop ${id}: not a missing skill`);
  const budgets = {};
  for (const id of Object.keys(kept).sort()) if (!drop.includes(id)) budgets[id] = kept[id];
  for (const id of acceptNew) budgets[id] = seedBudget(skills[id], policy);
  return { note: NOTE, policy, budgets: Object.fromEntries(Object.entries(budgets).sort(([a], [b]) => (a < b ? -1 : 1))), skills, pack: [...pack].sort() };
}

export const readLock = (path = LOCK_PATH) => JSON.parse(readFileSync(path, 'utf8'));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = (name, fallback) => {
    const i = process.argv.indexOf(name);
    return i > 0 ? process.argv[i + 1] : fallback;
  };
  const all = (name) => process.argv.flatMap((a, i) => (a === name && process.argv[i + 1] ? [process.argv[i + 1]] : []));
  const lockPath = arg('--lock', LOCK_PATH);
  const skillsDir = arg('--skills', join(ROOT, 'plugin', 'skills'));
  const previous = existsSync(lockPath) ? readLock(lockPath) : {};
  const acceptNew = all('--accept-new');
  const drop = all('--drop');
  const lock = buildLock({ skillsDir, pack: process.argv.includes('--no-pack') ? previous.pack ?? [] : packFiles(), previous, acceptNew, drop });
  const broken = budgetViolations(lock.skills, lock.budgets, lock.policy);
  if (broken.length) {
    console.log(`skills.lock.json not written: ${broken.length} budget violation(s)\n${broken.join('\n')}`);
    process.exitCode = 1;
  } else {
    const text = `${JSON.stringify(lock, null, 2)}\n`;
    const same = existsSync(lockPath) && readFileSync(lockPath, 'utf8') === text;
    if (!same) writeFileSync(lockPath, text);
    for (const id of acceptNew) {
      const b = lock.budgets[id];
      console.log(`seeded budget: ${id} (SKILL.md ${b.minSkillBytes}-${b.maxSkillBytes} B, ${b.minFiles}-${b.maxFiles} files, ${b.maxBytes} B in all)`);
    }
    for (const id of drop) console.log(`dropped budget: ${id}`);
    console.log(`skills.lock.json: ${same ? 'already current' : 'updated'} (${Object.keys(lock.skills).length} skills, ${lock.pack.length} packed files)`);
  }
}
